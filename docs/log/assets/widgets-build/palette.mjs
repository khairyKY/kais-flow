// widgets-build (2026-10-26): palette C for the home-screen widgets, read from the web app's tokens (the source of
// truth: app/src/styles/tokens/colors.css + colors.dark.css, --blk-<swatch> / --blk-<swatch>-ink / --blk-fill) and
// written as Android resources. Nothing is invented: a block's fill is its accent mixed into the card's paper at
// --blk-fill (24% by day, 20% at night), its edge the accent at 45%, exactly as the calendar's CSS mixes them.
//   node docs/log/assets/widgets-build/palette.mjs   (re-run whenever palette C changes)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..')
const TOK = path.join(ROOT, 'app/src/styles/tokens')
const RES = path.join(ROOT, 'app/native/android/res')

function read(file) {
  const css = fs.readFileSync(path.join(TOK, file), 'utf8')
  const v = (name) => css.match(new RegExp(`--${name}:\s*([^;]+);`))?.[1].trim()
  const sw = [...css.matchAll(/--blk-([a-z]+):\s*(#[0-9A-Fa-f]{6});\s*--blk-\1-ink:\s*(#[0-9A-Fa-f]{6});/g)].map((m) => ({ name: m[1], c: m[2], ink: m[3] }))
  return { sw, fill: parseFloat(v('blk-fill')) / 100, paper: v('paper-parchment') }
}
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
const hex = (c) => c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('').toUpperCase()
const mix = (a, b, t) => '#' + hex(rgb(a).map((v, i) => v * t + rgb(b)[i] * (1 - t)))

const day = read('colors.css')
const night = read('colors.dark.css')
if (day.sw.length !== 16 || night.sw.length !== 16) throw new Error(`expected 16 swatches, got ${day.sw.length} / ${night.sw.length}`)

const xml = (t, src) => {
  const rows = t.sw.flatMap((s) => [
    `    <color name="kfw_blk_${s.name}">${s.c}</color>`,
    `    <color name="kfw_blk_${s.name}_ink">${s.ink}</color>`,
    `    <color name="kfw_blk_${s.name}_fill">${mix(s.c, t.paper, t.fill)}</color>`,
    `    <color name="kfw_blk_${s.name}_edge">#73${s.c.slice(1).toUpperCase()}</color>`,
  ])
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by docs/log/assets/widgets-build/palette.mjs from ${src}: palette C (accent, its text tone,\n     the fill = accent at ${Math.round(t.fill * 100)}% over the paper, the edge = accent at 45%). Don't edit by hand. -->\n<resources>\n${rows.join('\n')}\n</resources>\n`
}
fs.writeFileSync(path.join(RES, 'values/kfw_palette.xml'), xml(day, 'app/src/styles/tokens/colors.css'))
fs.writeFileSync(path.join(RES, 'values-night/kfw_palette.xml'), xml(night, 'app/src/styles/tokens/colors.dark.css'))
for (const s of day.sw) {
  fs.writeFileSync(path.join(RES, `drawable/kfw_blk_${s.name}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- A palette C block (generated by docs/log/assets/widgets-build/palette.mjs): fill, 1dp edge, the block radius. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="@color/kfw_blk_${s.name}_fill" />
    <stroke android:width="1dp" android:color="@color/kfw_blk_${s.name}_edge" />
    <corners android:radius="@dimen/kfw_r_block" />
</shape>
`)
}
console.log('palette C:', day.sw.map((s) => s.name).join(' '))
