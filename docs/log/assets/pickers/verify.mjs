const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

// Cairo calendar, like the app (B2)
const cairoKey = (d) => new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Cairo' }).format(d)
const addDays = (k, n) => { const [y, m, d] = k.split('-').map(Number); return new Date(Date.UTC(y, m - 1, d + n)).toISOString().slice(0, 10) }
const today = cairoKey(new Date())
const tomorrow = addDays(today, 1)
const WD = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']
const wd = (k) => WD[new Date(k + 'T12:00:00Z').getUTCDay()]
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']

const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const phone = { viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true }
const desktop = { viewport: { width: 1280, height: 800 } }

async function open(view, theme) {
  const ctx = await browser.newContext({ ...view, deviceScaleFactor: 1 })
  await ctx.addInitScript((t) => localStorage.setItem('kf_theme', t), theme)
  const page = await ctx.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(`${BASE}/design-system`, { waitUntil: 'networkidle' })
  await page.locator('[data-demo="pick-date"]').scrollIntoViewIfNeeded()
  return { ctx, page, errors }
}
// token → computed rgb, and an element's computed style
const tok = (page, name) => page.evaluate((n) => {
  const e = document.createElement('div')
  e.style.color = `var(${n})`
  document.body.append(e)
  const c = getComputedStyle(e).color
  e.remove()
  return c
}, name)
