// The privacy policy, served from the app's own domain too (app/public/privacy.html): Google's OAuth
// consent screen needs a homepage and a privacy-policy URL on an authorized domain, and the app's
// domain is the one that's live. Generated from the built site page — run after `node build.mjs`:
//   node tools/app-privacy.mjs
import fs from 'node:fs'
const page = fs.readFileSync(new URL('../dist/privacy/index.html', import.meta.url), 'utf8')
const main = page.match(/<main[\s\S]*?<\/main>/)?.[0]
if (!main) throw new Error('no <main> in dist/privacy/index.html')
const out = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Privacy policy · Kai’s Flow</title>
<!-- Generated by site/tools/app-privacy.mjs from the site's privacy page. Edit site/src/pages/info.mjs, not this. -->
<style>
body{margin:0;background:#f6f1e7;color:#3b3127;font:17px/1.6 Georgia,'Times New Roman',serif}
main{max-width:680px;margin:0 auto;padding:40px 20px 64px}
h1{font-weight:400;font-size:34px;line-height:1.2;margin:.2em 0 .4em}
h2{font-weight:400;font-size:23px;margin:1.8em 0 .3em}
h2 small{font:12px/1 ui-monospace,Menlo,monospace;letter-spacing:.08em;margin-right:.6em;color:#8a7d6b}
p{margin:.6em 0}a{color:#9a4a2c}img,svg{display:none}
.todo{background:#f3e3b8;padding:0 .3em}
@media (prefers-color-scheme:dark){body{background:#1c1a17;color:#e8e0d2}a{color:#e2a07f}.todo{background:#5a4a20}}
</style></head><body>
${main}
<p style="text-align:center;padding:0 20px 40px"><a href="/">Open Kai’s Flow</a></p>
</body></html>
`
fs.writeFileSync(new URL('../../app/public/privacy.html', import.meta.url), out)
console.log('wrote app/public/privacy.html', out.length, 'bytes')
